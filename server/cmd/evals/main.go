// Command evals scores the duress detectors over the labeled dialogs in
// server/evals/duress_dialogs.jsonl, checks the call-context extraction
// (#106) over server/evals/ficha_dialogs.jsonl, and writes the report that is
// committed as server/evals/results.md:
//
//	cd server && go run ./cmd/evals
//
// It runs Rules, the LLM alone and Chain (the production detector), and
// scores the dialogs without a safe phrase (the #19/#22 set) apart from the
// ones with one (#106). The LLM runs need ANTHROPIC_API_KEY (and optionally
// DURESS_LLM_MODEL); without a key the LLM-only run and the extraction are
// skipped and Chain shows its rules fallback, and the report says the LLM was
// not measured.
package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
	"time"

	"github.com/platanus-hack/platanus-hack-26-ve-team-27/server/internal/config"
	"github.com/platanus-hack/platanus-hack-26-ve-team-27/server/internal/duress"
)

func main() {
	dialogsPath := flag.String("dialogs", "evals/duress_dialogs.jsonl", "labeled dialogs (JSONL)")
	fichaPath := flag.String("ficha", "evals/ficha_dialogs.jsonl", "call-context dialogs (JSONL)")
	out := flag.String("out", "evals/results.md", `report file to write; "" prints only`)
	timeout := flag.Duration("timeout", duress.DefaultLLMTimeout, "deadline of each LLM call")
	flag.Parse()

	dialogs, err := duress.LoadEvalDialogs(*dialogsPath)
	if err != nil {
		log.Fatal(err)
	}
	fichas, err := duress.LoadEvalFichaDialogs(*fichaPath)
	if err != nil {
		log.Fatal(err)
	}
	cfg := config.Load()
	model := cfg.Anthropic.DuressModel
	if model == "" {
		model = duress.DefaultModel
	}
	llm := duress.LLM{APIKey: cfg.Anthropic.APIKey, Model: model}
	hasKey := llm.APIKey != ""

	type run struct {
		name string
		det  duress.Detector
	}
	runs := []run{{"Rules", duress.Rules{}}}
	if hasKey {
		runs = append(runs, run{"LLM only (" + model + ")", llm})
	}
	runs = append(runs, run{"Chain (rules, then LLM on unclear)", duress.Chain{LLM: llm, Timeout: *timeout}})

	legacy, safe := splitBySafePhrase(dialogs)
	var b strings.Builder
	b.WriteString("# Duress detector eval results\n\n")
	b.WriteString("Generated by `cd server && go run ./cmd/evals`; do not edit by hand.\n\n")
	fmt.Fprintf(&b, "- Date: %s\n", time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintf(&b, "- Dialogs: %d from `%s`: %d without a safe phrase (%d labeled duress) and %d with one (%d labeled duress)\n",
		len(dialogs), *dialogsPath, len(legacy), countDuress(legacy), len(safe), countDuress(safe))
	fmt.Fprintf(&b, "- Call-context dialogs: %d from `%s`\n", len(fichas), *fichaPath)
	if hasKey {
		fmt.Fprintf(&b, "- LLM: `%s`, %v timeout per call\n", model, *timeout)
	} else {
		b.WriteString("- LLM: **not measured**. ANTHROPIC_API_KEY was not set, so the LLM-only run and the call-context " +
			"extraction were skipped and Chain shows the rules fallback on every unclear call. Re-run with a key to measure it.\n")
	}
	b.WriteString("- Positive class: duress. *Strict* alerts only on a duress verdict; *alert* also alerts on unclear, " +
		"which is what the family sees: the notifier sends unclear calls. An LLM error never alerts.\n")
	b.WriteString("- With a safe phrase, \"said neither phrase\" is unclear by design (the person did not confirm they are fine), " +
		"so those dialogs count as false alarms under *alert*; the `expect` column checks the verdict each one must get.\n\n")

	ctx := context.Background()
	results := make([][]outcome, len(runs))
	for i, r := range runs {
		for _, d := range dialogs {
			res, err := detect(ctx, r.det, d, *timeout)
			o := outcome{ID: d.ID, Duress: d.Duress, Pred: string(res.Verdict), Reason: res.Reason}
			if err != nil {
				o.Pred, o.Reason = predError, err.Error()
			}
			results[i] = append(results[i], o)
		}
	}

	fmt.Fprintf(&b, "## Without a safe phrase (%d dialogs)\n\n", len(legacy))
	b.WriteString("The #19/#22 set. The rules' numbers here must not change with #106.\n\n")
	for i, r := range runs {
		outs, ds := pick(results[i], dialogs, false)
		b.WriteString(scoreOutcomes(outs).markdown(r.name))
		b.WriteString("\n")
		b.WriteString(reasons(outs, ds))
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "## With a safe phrase (%d dialogs, #106)\n\n", len(safe))
	for i, r := range runs {
		outs, ds := pick(results[i], dialogs, true)
		b.WriteString(scoreOutcomes(outs).markdown(r.name))
		b.WriteString("\n")
		b.WriteString(expectTable(outs, ds))
		b.WriteString("\n")
	}

	b.WriteString("## Call context (#106)\n\n")
	if !hasKey {
		b.WriteString("**Not measured**: the extraction needs ANTHROPIC_API_KEY.\n")
	} else {
		var rows []fichaRow
		for _, f := range fichas {
			d := f.Dialog()
			c, err := duress.ExtractContext(ctx, llm, *timeout, d.Transcript(), d.Phrases())
			rows = append(rows, fichaRow{dialog: f, ctx: c, err: err})
		}
		b.WriteString(fichaMarkdown(rows))
	}

	report := b.String()
	fmt.Print(report)
	if *out != "" {
		if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", *out)
	}
}

// splitBySafePhrase splits dialogs into those without a safe phrase and
// those with one.
func splitBySafePhrase(dialogs []duress.EvalDialog) (without, with []duress.EvalDialog) {
	for _, d := range dialogs {
		if d.SafePhrase == "" {
			without = append(without, d)
		} else {
			with = append(with, d)
		}
	}
	return without, with
}

// pick returns the outcomes and dialogs with (or without) a safe phrase, in
// the same order.
func pick(outs []outcome, dialogs []duress.EvalDialog, withSafe bool) ([]outcome, []duress.EvalDialog) {
	var picked []outcome
	var ds []duress.EvalDialog
	for i, d := range dialogs {
		if (d.SafePhrase != "") == withSafe {
			picked = append(picked, outs[i])
			ds = append(ds, d)
		}
	}
	return picked, ds
}

// detect runs one dialog with the same per-call deadline Chain uses, so the
// LLM-only run can't hang either.
func detect(ctx context.Context, det duress.Detector, d duress.EvalDialog, timeout time.Duration) (duress.Result, error) {
	ctx, cancel := context.WithTimeout(ctx, timeout+time.Second)
	defer cancel()
	return det.Detect(ctx, d.Transcript(), d.Phrases())
}

func countDuress(dialogs []duress.EvalDialog) int {
	n := 0
	for _, d := range dialogs {
		if d.Duress {
			n++
		}
	}
	return n
}

// expectTable lists every dialog's expected and actual verdict, and how many
// match.
func expectTable(outs []outcome, dialogs []duress.EvalDialog) string {
	var b strings.Builder
	b.WriteString("| id | kind | expect | verdict | ok | reason |\n| --- | --- | --- | --- | --- | --- |\n")
	match, labeled := 0, 0
	for i, o := range outs {
		d := dialogs[i]
		ok := ""
		if d.Expect != "" {
			labeled++
			ok = "no"
			if o.Pred == string(d.Expect) {
				match++
				ok = "yes"
			}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", o.ID, d.Kind, d.Expect, o.Pred, ok,
			strings.ReplaceAll(o.Reason, "|", `\|`))
	}
	fmt.Fprintf(&b, "\n- Verdict as expected: %d of %d\n", match, labeled)
	return b.String()
}

// reasons lists the verdict and reason of every dialog that was not a clean
// hit, so a reviewer sees why without re-running.
func reasons(outs []outcome, dialogs []duress.EvalDialog) string {
	var b strings.Builder
	for i, o := range outs {
		clean := (o.Duress && o.Pred == "duress") || (!o.Duress && o.Pred == "no_duress")
		if clean {
			continue
		}
		if b.Len() == 0 {
			b.WriteString("| id | kind | label | verdict | reason |\n| --- | --- | --- | --- | --- |\n")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", o.ID, dialogs[i].Kind, label(o.Duress), o.Pred,
			strings.ReplaceAll(o.Reason, "|", `\|`))
	}
	return b.String()
}
