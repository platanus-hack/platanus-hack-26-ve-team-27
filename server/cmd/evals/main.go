// Command evals scores the duress detectors over the labeled dialogs in
// server/evals/duress_dialogs.jsonl and writes the report that is committed
// as server/evals/results.md:
//
//	cd server && go run ./cmd/evals
//
// It runs Rules, the LLM alone and Chain (the production detector). The LLM
// runs need ANTHROPIC_API_KEY (and optionally DURESS_LLM_MODEL); without a
// key the LLM-only run is skipped and Chain shows its rules fallback, and the
// report says the LLM was not measured.
package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
	"time"

	"github.com/platanus-hack/platanus-hack-26-ve-team-27/server/internal/config"
	"github.com/platanus-hack/platanus-hack-26-ve-team-27/server/internal/duress"
)

func main() {
	dialogsPath := flag.String("dialogs", "evals/duress_dialogs.jsonl", "labeled dialogs (JSONL)")
	out := flag.String("out", "evals/results.md", `report file to write; "" prints only`)
	timeout := flag.Duration("timeout", duress.DefaultLLMTimeout, "deadline of each LLM call")
	flag.Parse()

	dialogs, err := duress.LoadEvalDialogs(*dialogsPath)
	if err != nil {
		log.Fatal(err)
	}
	cfg := config.Load()
	model := cfg.Anthropic.DuressModel
	if model == "" {
		model = duress.DefaultModel
	}
	llm := duress.LLM{APIKey: cfg.Anthropic.APIKey, Model: model}
	hasKey := llm.APIKey != ""

	type run struct {
		name string
		det  duress.Detector
	}
	runs := []run{{"Rules", duress.Rules{}}}
	if hasKey {
		runs = append(runs, run{"LLM only (" + model + ")", llm})
	}
	runs = append(runs, run{"Chain (rules, then LLM on unclear)", duress.Chain{LLM: llm, Timeout: *timeout}})

	var b strings.Builder
	b.WriteString("# Duress detector eval results\n\n")
	b.WriteString("Generated by `cd server && go run ./cmd/evals`; do not edit by hand.\n\n")
	fmt.Fprintf(&b, "- Date: %s\n", time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintf(&b, "- Dialogs: %d from `%s` (%d labeled duress)\n", len(dialogs), *dialogsPath, countDuress(dialogs))
	if hasKey {
		fmt.Fprintf(&b, "- LLM: `%s`, %v timeout per call\n", model, *timeout)
	} else {
		b.WriteString("- LLM: **not measured**. ANTHROPIC_API_KEY was not set, so the LLM-only run was skipped and " +
			"Chain shows the rules fallback on every unclear call. Re-run with a key to measure it.\n")
	}
	b.WriteString("- Positive class: duress. *Strict* alerts only on a duress verdict; *alert* also alerts on unclear, " +
		"which is what the family sees if the notifier forwards unclear calls. An LLM error never alerts.\n\n")
	b.WriteString("## Detectors\n\n")

	ctx := context.Background()
	for _, r := range runs {
		var outs []outcome
		for _, d := range dialogs {
			res, err := detect(ctx, r.det, d, *timeout)
			o := outcome{ID: d.ID, Duress: d.Duress, Pred: string(res.Verdict), Reason: res.Reason}
			if err != nil {
				o.Pred, o.Reason = predError, err.Error()
			}
			outs = append(outs, o)
		}
		b.WriteString(scoreOutcomes(outs).markdown(r.name))
		b.WriteString("\n")
		b.WriteString(reasons(outs, dialogs))
		b.WriteString("\n")
	}

	report := b.String()
	fmt.Print(report)
	if *out != "" {
		if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", *out)
	}
}

// detect runs one dialog with the same per-call deadline Chain uses, so the
// LLM-only run can't hang either.
func detect(ctx context.Context, det duress.Detector, d duress.EvalDialog, timeout time.Duration) (duress.Result, error) {
	ctx, cancel := context.WithTimeout(ctx, timeout+time.Second)
	defer cancel()
	return det.Detect(ctx, d.Transcript(), d.DuressPhrase)
}

func countDuress(dialogs []duress.EvalDialog) int {
	n := 0
	for _, d := range dialogs {
		if d.Duress {
			n++
		}
	}
	return n
}

// reasons lists the verdict and reason of every dialog that was not a clean
// hit, so a reviewer sees why without re-running.
func reasons(outs []outcome, dialogs []duress.EvalDialog) string {
	var b strings.Builder
	for i, o := range outs {
		clean := (o.Duress && o.Pred == "duress") || (!o.Duress && o.Pred == "no_duress")
		if clean {
			continue
		}
		if b.Len() == 0 {
			b.WriteString("| id | kind | label | verdict | reason |\n| --- | --- | --- | --- | --- |\n")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", o.ID, dialogs[i].Kind, label(o.Duress), o.Pred,
			strings.ReplaceAll(o.Reason, "|", `\|`))
	}
	return b.String()
}
